// compartida, sin migración), con dos typos: la tabla "InscripcionTUrno" y las columnas
// "createdAT"/"updatedAT" de Turnos. Por eso esta migración es idempotente: donde ya existen las
// corrige y las completa, y en una base vacía las crea desde cero.
//
// Reglas del esquema:
// - Al borrar un cliente se borran sus inscripciones.
// - Un profesor con turnos asignados no se puede borrar (igual que con rutinas).
// - Un profesor no se asigna dos veces al mismo turno, y un cliente no se inscribe dos veces
//   al mismo turno con una inscripción vigente.
